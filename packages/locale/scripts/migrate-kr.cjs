const result = {}
let exact = 0,
  alias = 0,
  airbetSwap = 0,
  lastSeg = 0,
  fallback = 0

for (const [key, enValue] of Object.entries(enRaw)) {
  // 1. exact match in legacy kr
  if (krRaw[key] !== undefined) {
    result[key] = krRaw[key]
    exact++
    continue
  }
  // 2. explicit alias
  if (ALIASES[key] && krRaw[ALIASES[key]] !== undefined) {
    result[key] = krRaw[ALIASES[key]]
    alias++
    continue
  }
  // 3. airbetMenu.* swap (en uses oribetMenu.)
  if (key.startsWith('oribetMenu.')) {
    const swap = 'airbetMenu.' + key.slice('oribetMenu.'.length)
    if (krRaw[swap] !== undefined) {
      result[key] = krRaw[swap]
      airbetSwap++
      continue
    }
  }
  // 4. last-segment match (skip too-generic segments where legacy bare value carried different meaning)
  const SEG_BLOCKLIST = new Set(['title', 'description', 'text', 'desc', 'name'])
  const seg = key.includes('.') ? key.slice(key.lastIndexOf('.') + 1) : key
  if (seg !== key && !SEG_BLOCKLIST.has(seg) && krRaw[seg] !== undefined) {
    result[key] = krRaw[seg]
    lastSeg++
    continue
  }
  // 5. English fallback
  result[key] = enValue
  fallback++
}

const out = JSON.stringify(result, null, 2) + '\n'
fs.writeFileSync(path.join(ROOT, 'kr.json'), out)

console.error(
  `wrote ${Object.keys(result).length} keys → exact=${exact} alias=${alias} airbet=${airbetSwap} lastSeg=${lastSeg} fallback=${fallback}`
)
